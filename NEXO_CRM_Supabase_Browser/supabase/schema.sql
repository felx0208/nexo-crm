insert into public.pipeline_stages(pipeline_id,name,position,probability,is_won,is_lost)
select p.id,s.name,s.position,s.probability,s.is_won,s.is_lost
from public.pipelines p
cross join (values
 ('Prospecção',1,10,false,false),
 ('Qualificação',2,25,false,false),
 ('Proposta',3,50,false,false),
 ('Negociação',4,75,false,false),
 ('Ganho',5,100,true,false),
 ('Perdido',6,0,false,true)
) as s(name,position,probability,is_won,is_lost)
where p.is_default=true
and not exists (select 1 from public.pipeline_stages ps where ps.pipeline_id=p.id and ps.position=s.position);

