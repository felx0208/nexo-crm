create index if not exists idx_tasks_status_due on public.tasks(status,due_at);
create index if not exists idx_tasks_assignee on public.tasks(assigned_to,status);

create table if not exists public.activities (
  id bigint generated by default as identity primary key,
  contact_id bigint references public.contacts(id) on update cascade on delete set null,
  deal_id bigint references public.deals(id) on update cascade on delete set null,
  user_id bigint references public.users(id) on update cascade on delete set null,
  type text not null default 'note' check (type in ('note','call','meeting','email','stage_change','status_change','other')),
