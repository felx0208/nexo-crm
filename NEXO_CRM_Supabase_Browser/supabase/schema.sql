create index if not exists idx_activities_contact_date on public.activities(contact_id,created_at desc);
create index if not exists idx_activities_deal_date on public.activities(deal_id,created_at desc);

create table if not exists public.data_import_jobs (
  id bigint generated by default as identity primary key,
  user_id bigint references public.users(id) on update cascade on delete set null,
  kind text not null check (kind in ('contacts_import','contacts_export')),
  status text not null default 'queued' check (status in ('queued','processing','completed','failed')),
  original_filename text, total_rows integer not null default 0,
  successful_rows integer not null default 0, failed_rows integer not null default 0,
  error_report jsonb, started_at timestamptz, finished_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Helpers executados com direitos controlados para consultar o perfil autenticado.
create or replace function public.current_app_user_id()
returns bigint language sql stable security definer set search_path = ''
as $$
  select u.id from public.users u
  where u.auth_user_id = auth.uid() and u.is_active = true
  limit 1
$$;

create or replace function public.current_app_role()
returns text language sql stable security definer set search_path = ''
as $$
  select u.role from public.users u
  where u.auth_user_id = auth.uid() and u.is_active = true
  limit 1
$$;

revoke all on function public.current_app_user_id() from public, anon;
revoke all on function public.current_app_role() from public, anon;
grant execute on function public.current_app_user_id() to authenticated;
grant execute on function public.current_app_role() to authenticated;

-- The first Auth user becomes administrator. Subsequent users created by the
-- project owner in Supabase Auth become sales users. Keep public sign-ups OFF.
create or replace function public.handle_new_auth_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare new_role text;
begin
  perform pg_advisory_xact_lock(718202610);
  if not exists (select 1 from public.users) then
    new_role := 'admin';
  else
    new_role := 'sales';
  end if;
  insert into public.users(auth_user_id,name,email,role,is_active)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'name',''), split_part(coalesce(new.email,''),'@',1), 'Usuário'),
    coalesce(new.email,''),
    new_role,
    true
  )
  on conflict (auth_user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_nexo on auth.users;
create trigger on_auth_user_created_nexo
after insert on auth.users
for each row execute function public.handle_new_auth_user();

-- Updated_at trigger
create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare t text;
begin
  foreach t in array array['users','company_settings','contacts','pipelines','pipeline_stages','deals','tasks','activities','data_import_jobs']
  loop
    execute format('drop trigger if exists set_updated_at_nexo on public.%I',t);
    execute format('create trigger set_updated_at_nexo before update on public.%I for each row execute function public.set_updated_at()',t);
  end loop;
end $$;

