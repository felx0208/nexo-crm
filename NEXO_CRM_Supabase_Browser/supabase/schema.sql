create table if not exists public.users (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete cascade,
  name text not null,
  email text not null,
  role text not null default 'sales' check (role in ('admin','manager','sales')),
  is_active boolean not null default true,
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.company_settings (
  id smallint primary key default 1 check (id = 1),
  name text not null,
  email text,
  phone text,
  currency char(3) not null default 'BRL',
  timezone text not null default 'America/Sao_Paulo',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  name text not null,
  company_name text,
  email text,
  phone text,
  source text,
  status text not null default 'lead' check (status in ('lead','prospect','negotiation','customer','inactive')),
  owner_id bigint references public.users(id) on update cascade on delete set null,
  notes text,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_contacts_status on public.contacts(status);
create index if not exists idx_contacts_owner on public.contacts(owner_id);
create index if not exists idx_contacts_name on public.contacts(name);

create table if not exists public.pipelines (
  id bigint generated by default as identity primary key,
  name text not null,
  is_default boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pipeline_stages (
  id bigint generated by default as identity primary key,
  pipeline_id bigint not null references public.pipelines(id) on update cascade on delete cascade,
  name text not null,
  position integer not null default 0,
  probability smallint not null default 0 check (probability between 0 and 100),
  is_won boolean not null default false,
  is_lost boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (pipeline_id, position),
  check (not (is_won and is_lost))
);

create table if not exists public.deals (
  id bigint generated by default as identity primary key,
  contact_id bigint not null references public.contacts(id) on update cascade on delete restrict,
  pipeline_id bigint not null references public.pipelines(id) on update cascade on delete restrict,
  stage_id bigint not null references public.pipeline_stages(id) on update cascade on delete restrict,
  title text not null,
  description text,
  value numeric(12,2) not null default 0 check (value >= 0),
  owner_id bigint references public.users(id) on update cascade on delete set null,
  expected_close_date date,
  closed_at timestamptz,
  lost_reason text,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_deals_contact on public.deals(contact_id);
create index if not exists idx_deals_pipeline_stage on public.deals(pipeline_id,stage_id);
create index if not exists idx_deals_owner on public.deals(owner_id);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  type text not null default 'other' check (type in ('call','meeting','email','follow_up','other')),
  status text not null default 'pending' check (status in ('pending','in_progress','completed','cancelled')),
  priority text not null default 'medium' check (priority in ('low','medium','high')),
  due_at timestamp without time zone,
  assigned_to bigint references public.users(id) on update cascade on delete set null,
  created_by bigint references public.users(id) on update cascade on delete set null,
  contact_id bigint references public.contacts(id) on update cascade on delete set null,
  deal_id bigint references public.deals(id) on update cascade on delete set null,
  completed_at timestamptz,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
